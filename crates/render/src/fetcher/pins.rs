/// Chrome for Testing's name for this build's platform. `None` where it
/// has no `chrome-headless-shell` (32-bit Windows, Linux on ARM).
pub fn current_platform() -> Option<&'static str> {
    if cfg!(all(target_os = "linux", target_arch = "x86_64")) {
        Some("linux64")
    } else if cfg!(all(target_os = "macos", target_arch = "aarch64")) {
        Some("mac-arm64")
    } else if cfg!(all(target_os = "macos", target_arch = "x86_64")) {
        Some("mac-x64")
    } else if cfg!(all(target_os = "windows", target_arch = "x86_64")) {
        Some("win64")
    } else {
        None
    }
}

/// The pin of a platform, `None` for an unknown one.
pub fn pin_for(platform: &str) -> Option<&'static Pin> {
    PINS.iter().find(|p| p.platform == platform)
}

/// The archive's address on Chrome for Testing.
pub fn archive_url(platform: &str) -> String {
    format!(
        "https://{HOST}/chrome-for-testing-public/{VERSION}/{platform}/chrome-headless-shell-{platform}.zip"
    )
}
