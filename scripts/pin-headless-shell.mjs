#!/usr/bin/env node
// Regenerates the pin table in crates/render/src/fetcher/pins.rs (research
// R14). Run at release time, with network access:
//
//   node scripts/pin-headless-shell.mjs [VERSION]
//
// Without VERSION it uses the Stable channel's version. It downloads each
// platform's chrome-headless-shell archive from Chrome for Testing,
// computes its size and SHA-256, and rewrites PINNED_VERSION in find.rs and the
// table between the BEGIN PINS and END PINS markers.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const PLATFORMS = ["linux64", "mac-arm64", "mac-x64", "win64"];
const HOST = "https://storage.googleapis.com/chrome-for-testing-public";
const FILE = fileURLToPath(new URL("../crates/render/src/fetcher/pins.rs", import.meta.url));
const FIND = fileURLToPath(new URL("../crates/render/src/find.rs", import.meta.url));

async function stableVersion() {
  const res = await fetch("https://googlechromelabs.github.io/chrome-for-testing/last-known-good-versions.json");
  if (!res.ok) throw new Error(`version lookup failed: HTTP ${res.status}`);
  return (await res.json()).channels.Stable.version;
}

async function pin(version, platform) {
  const url = `${HOST}/${version}/${platform}/chrome-headless-shell-${platform}.zip`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const hash = createHash("sha256");
  let bytes = 0;
  for await (const chunk of res.body) {
    hash.update(chunk);
    bytes += chunk.length;
  }
  return { platform, bytes, sha256: hash.digest("hex") };
}

const group = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, "_");

const version = process.argv[2] ?? (await stableVersion());
const pins = [];
for (const p of PLATFORMS) {
  console.error(`pinning ${version} ${p} ...`);
  pins.push(await pin(version, p));
}
const table = pins
  .map(
    (p) => `    Pin {
        platform: "${p.platform}",
        bytes: ${group(p.bytes)},
        sha256: "${p.sha256}",
    },`,
  )
  .join("\n");
let src = readFileSync(FILE, "utf8");
src = src.replace(
  /\/\/ BEGIN PINS[^\n]*\n[\s\S]*?\/\/ END PINS/,
  `// BEGIN PINS (generated by scripts/pin-headless-shell.mjs)\npub const PINS: &[Pin] = &[\n${table}\n];\n// END PINS`,
);
writeFileSync(FILE, src);
writeFileSync(
  FIND,
  readFileSync(FIND, "utf8").replace(/pub const PINNED_VERSION: &str = "[^"]*";/, `pub const PINNED_VERSION: &str = "${version}";`),
);
console.error(`wrote ${FILE} and ${FIND}`);
