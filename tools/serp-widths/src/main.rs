//! Generates the advance-width table behind `px_width` (spec 027 plan D1).
//!
//! Run from the repository root:
//! `cargo run --manifest-path tools/serp-widths/Cargo.toml`
//!
//! Widths come from Liberation Sans (metric-compatible with Arial, the font
//! search results use), with Noto Sans Hebrew and Noto Sans Arabic for
//! characters it lacks. They are written in thousandths of an em, so one
//! table serves every font size. Characters outside the table use the
//! per-script fallbacks in `crates/results/src/serp/mod.rs`.

use std::fmt::Write as _;
use std::fs;

/// Unicode ranges measured from the fonts.
const RANGES: &[(u32, u32)] = &[
    (0x0020, 0x007E), // Basic Latin
    (0x00A0, 0x024F), // Latin-1 Supplement, Latin Extended-A and -B
    (0x0250, 0x02FF), // IPA, spacing modifiers
    (0x0300, 0x036F), // combining diacritics
    (0x0370, 0x03FF), // Greek
    (0x0400, 0x052F), // Cyrillic
    (0x0590, 0x05FF), // Hebrew
    (0x0600, 0x06FF), // Arabic
    (0x0750, 0x077F), // Arabic Supplement
    (0x1E00, 0x1EFF), // Latin Extended Additional
    (0x2000, 0x206F), // General Punctuation
    (0x20A0, 0x20CF), // Currency
    (0x2100, 0x214F), // Letterlike
    (0x2190, 0x21FF), // Arrows
    (0xFB1D, 0xFB4F), // Hebrew presentation forms
];

const FONTS: &[&str] = &[
    "tools/serp-widths/fonts/LiberationSans-Regular.ttf",
    "tools/serp-widths/fonts/NotoSansHebrew-Regular.ttf",
    "tools/serp-widths/fonts/NotoSansArabic-Regular.ttf",
];

const RUST_OUT: &str = "crates/results/src/serp/widths.rs";
const JSON_OUT: &str = "ui/src/generated/serpWidths.json";

fn main() {
    let data: Vec<Vec<u8>> = FONTS
        .iter()
        .map(|p| fs::read(p).unwrap_or_else(|e| panic!("{p}: {e} (run from the repository root)")))
        .collect();
    let faces: Vec<ttf_parser::Face> = data
        .iter()
        .map(|d| ttf_parser::Face::parse(d, 0).expect("font parses"))
        .collect();

    let mut table: Vec<(u32, u16)> = Vec::new();
    for &(start, end) in RANGES {
        for cp in start..=end {
            let Some(ch) = char::from_u32(cp) else { continue };
            let width = faces.iter().find_map(|f| {
                let g = f.glyph_index(ch)?;
                let adv = f.glyph_hor_advance(g)?;
                Some((f64::from(adv) * 1000.0 / f64::from(f.units_per_em())).round() as u16)
            });
            if let Some(w) = width {
                table.push((cp, w));
            }
        }
    }

    let arabic = arabic_forms(&faces);
    let lam_alef = lam_alef_forms(&faces);

    let mut rust = String::from(
        "// @generated by tools/serp-widths. Do not edit; re-run the generator.\n\
         //! Advance widths in thousandths of an em, sorted by code point.\n\n\
         pub(super) const WIDTHS: &[(u32, u16)] = &[\n",
    );
    for chunk in table.chunks(6) {
        rust.push_str("   ");
        for (cp, w) in chunk {
            write!(rust, " (0x{cp:04X}, {w}),").unwrap();
        }
        rust.push('\n');
    }
    rust.push_str("];\n\n");
    rust.push_str(
        "/// Arabic letters: (letter, isolated, final, initial, medial, joins both sides).\n\
         pub(super) const ARABIC: &[(u32, u16, u16, u16, u16, bool)] = &[\n",
    );
    for (cp, [i, f, n, m], dual) in &arabic {
        writeln!(rust, "    (0x{cp:04X}, {i}, {f}, {n}, {m}, {dual}),").unwrap();
    }
    rust.push_str("];\n\n/// Lam followed by an alef: (alef, isolated ligature, final ligature).\n");
    rust.push_str("pub(super) const LAM_ALEF: &[(u32, u16, u16)] = &[\n");
    for (cp, i, f) in &lam_alef {
        writeln!(rust, "    (0x{cp:04X}, {i}, {f}),").unwrap();
    }
    rust.push_str("];\n");
    fs::write(RUST_OUT, rust).expect("write Rust table");

    let mut json = String::from("{\"widths\":[");
    for (i, (cp, w)) in table.iter().enumerate() {
        if i > 0 {
            json.push(',');
        }
        write!(json, "[{cp},{w}]").unwrap();
    }
    json.push_str("],\"arabic\":[");
    for (i, (cp, [a, b, c, d], dual)) in arabic.iter().enumerate() {
        if i > 0 {
            json.push(',');
        }
        write!(json, "[{cp},{a},{b},{c},{d},{}]", u8::from(*dual)).unwrap();
    }
    json.push_str("],\"lamAlef\":[");
    for (i, (cp, a, b)) in lam_alef.iter().enumerate() {
        if i > 0 {
            json.push(',');
        }
        write!(json, "[{cp},{a},{b}]").unwrap();
    }
    json.push_str("]}\n");
    fs::write(JSON_OUT, json).expect("write JSON table");

    eprintln!("{} characters", table.len());
}

fn advance(faces: &[ttf_parser::Face], ch: char) -> Option<u16> {
    faces.iter().find_map(|f| {
        let g = f.glyph_index(ch)?;
        let adv = f.glyph_hor_advance(g)?;
        Some((f64::from(adv) * 1000.0 / f64::from(f.units_per_em())).round() as u16)
    })
}

/// Arabic letters drawn in context. The presentation-forms block lists each
/// letter's forms in order: isolated, final, then initial and medial for
/// letters that join on both sides. Their widths stand in for the shaped
/// glyphs a browser draws.
fn arabic_forms(faces: &[ttf_parser::Face]) -> Vec<(u32, [u16; 4], bool)> {
    use unicode_normalization::UnicodeNormalization;
    let mut groups: Vec<(char, Vec<u16>)> = Vec::new();
    for cp in 0xFE80..=0xFEF4u32 {
        let Some(form) = char::from_u32(cp) else { continue };
        let base: Vec<char> = form.to_string().nfkd().collect();
        let [base] = base[..] else { continue };
        let Some(w) = advance(&faces[2..], form) else { continue };
        match groups.last_mut() {
            Some((b, ws)) if *b == base => ws.push(w),
            _ => groups.push((base, vec![w])),
        }
    }
    groups
        .into_iter()
        .filter_map(|(base, ws)| match ws[..] {
            [i, f] => Some((base as u32, [i, f, i, f], false)),
            [i, f, n, m] => Some((base as u32, [i, f, n, m], true)),
            _ => None,
        })
        .collect()
}

fn lam_alef_forms(faces: &[ttf_parser::Face]) -> Vec<(u32, u16, u16)> {
    // FEF5..FEFC: isolated and final ligatures of lam with each alef.
    [(0x0622u32, 0xFEF5u32), (0x0623, 0xFEF7), (0x0625, 0xFEF9), (0x0627, 0xFEFB)]
        .into_iter()
        .filter_map(|(alef, lig)| {
            let i = advance(&faces[2..], char::from_u32(lig)?)?;
            let f = advance(&faces[2..], char::from_u32(lig + 1)?)?;
            Some((alef, i, f))
        })
        .collect()
}
